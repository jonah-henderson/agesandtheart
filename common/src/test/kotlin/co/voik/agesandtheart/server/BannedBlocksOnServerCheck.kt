package co.voik.agesandtheart.server

import io.kotest.core.annotation.Tags
import io.kotest.core.spec.style.FunSpec

/**
 * A block a book banned is generated nowhere in its Age — `no snow` in a frozen one — however the ground would have
 * laid it. A server check because only generating a chunk can show it. Counted by a `fill` that clears the block
 * from the ground's layers, which says how many it cleared.
 */
@Tags(NEEDS_SERVER)
class BannedBlocksOnServerCheck : FunSpec({

    val server = DrivenServer.shared

    fun inThe(age: String, command: String) = server.run("execute in agesandtheart:$age run $command")

    fun snowIn(age: String, sentence: String): Int {
        server.run("age write $age $SEED $sentence")
        inThe(age, "forceload add $FAR $FAR ${FAR + CHUNK} ${FAR + CHUNK}")
        server.waitUntil("the frozen chunks loading in '$age'") {
            inThe(age, "execute if loaded ${FAR + CHUNK} $LOWEST ${FAR + CHUNK}").startsWith("Test passed")
        }
        val cleared = (0..1).sumOf { across ->
            (0..1).sumOf { down ->
                val x = FAR + across * CHUNK
                val z = FAR + down * CHUNK
                val said = inThe(age, "fill $x $LOWEST $z ${x + CHUNK - 1} $HIGHEST ${z + CHUNK - 1} minecraft:air replace minecraft:snow")
                Regex("filled (\\d+)").find(said)?.groupValues?.get(1)?.toInt() ?: 0
            }
        }
        inThe(age, "forceload remove all")
        return cleared
    }

    test("a frozen Age that banned snow generates none, where one that did not lays it everywhere") {
        check(snowIn(SNOWY, "frozen age") > 0) { "a frozen Age laid no snow, so this check sees nothing" }
        check(snowIn(SNOWLESS, "frozen age no snow") == 0) { "a frozen Age that banned snow laid some" }
    }
})

private const val SEED = 4786177076396069349L
private const val SNOWY = "snowyage"
private const val SNOWLESS = "snowlessage"

/** Far from the origin, where nothing has been generated by anything else. */
private const val FAR = 5008
private const val CHUNK = 16

/** The layers ordinary ground stands in; a fill takes at most 32768 blocks, and this is 16384. */
private const val LOWEST = 60
private const val HIGHEST = 123
