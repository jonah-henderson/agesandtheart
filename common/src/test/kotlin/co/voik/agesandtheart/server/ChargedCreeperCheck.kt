package co.voik.agesandtheart.server

import io.kotest.core.annotation.Tags
import io.kotest.core.spec.style.FunSpec

/**
 * A creeper an Age wrote charged comes into it powered, and one in an Age that said nothing of it does not.
 * A server check because the charge is laid on as the creeper enters the level, which only a level can show.
 */
@Tags(NEEDS_SERVER)
class ChargedCreeperCheck : FunSpec({

    val server = DrivenServer.shared

    fun inThe(age: String, command: String) = server.run("execute in agesandtheart:$age run $command")

    fun summonsAChargedCreeper(age: String, sentence: String): Boolean {
        server.run("age write $age $SEED $sentence")
        inThe(age, "forceload add $FAR $FAR")
        server.waitUntil("the chunk a creeper is summoned into loading in '$age'") {
            inThe(age, "execute if loaded $FAR $PROBE_HEIGHT $FAR").startsWith("Test passed")
        }
        inThe(age, "summon minecraft:creeper $FAR $PROBE_HEIGHT $FAR {NoAI:1b}")
        val charged = inThe(age, "execute if entity @e[distance=0..,type=minecraft:creeper,nbt={powered:1b}]")
        inThe(age, "forceload remove all")
        return charged.startsWith("Test passed")
    }

    test("a creeper summoned into a charged-creeper Age is powered, and one elsewhere is not") {
        check(!summonsAChargedCreeper(UNCHARGED, "age creeper")) { "a creeper came powered where nothing charged it" }
        check(summonsAChargedCreeper(CHARGED, "age charged creeper")) { "a creeper in 'charged creeper' came unpowered" }
    }
})

private const val SEED = 4786177076396069349L
private const val CHARGED = "chargedcreepers"
private const val UNCHARGED = "plaincreepers"

/** Far from the origin, where nothing has been generated by anything else. */
private const val FAR = 5000
private const val PROBE_HEIGHT = 64
