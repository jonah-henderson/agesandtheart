package co.voik.agesandtheart.server

import io.kotest.core.annotation.Tags
import io.kotest.core.spec.style.FunSpec

/**
 * Trees an Age wrote grown of a block grow it where their leaves would be — `diamond_block trees`. A server check
 * because the block is set as a tree is placed, which only generating a chunk can show. Counted by a `fill` that
 * clears the block from the canopy's layers, which says how many it cleared.
 */
@Tags(NEEDS_SERVER)
class TreeFoliageOnServerCheck : FunSpec({

    val server = DrivenServer.shared

    fun inThe(age: String, command: String) = server.run("execute in agesandtheart:$age run $command")

    test("trees written of diamond blocks grow diamond blocks where their leaves would be") {
        server.run("age write $AGE $SEED age diamond_block trees forest")
        inThe(AGE, "forceload add $FAR $FAR ${FAR + CHUNK} ${FAR + CHUNK}")
        server.waitUntil("the forest's chunks loading in '$AGE'") {
            inThe(AGE, "execute if loaded ${FAR + CHUNK} $LOWEST ${FAR + CHUNK}").startsWith("Test passed")
        }
        val cleared = (0..1).sumOf { across ->
            (0..1).sumOf { down ->
                val x = FAR + across * CHUNK
                val z = FAR + down * CHUNK
                val said = inThe(AGE, "fill $x $LOWEST $z ${x + CHUNK - 1} $HIGHEST ${z + CHUNK - 1} minecraft:air replace minecraft:diamond_block")
                Regex("filled (\\d+)").find(said)?.groupValues?.get(1)?.toInt() ?: 0
            }
        }
        inThe(AGE, "forceload remove all")
        check(cleared > 0) { "a forest of diamond trees grew no diamond blocks in four chunks" }
    }
})

private const val SEED = 4786177076396069349L
private const val AGE = "diamondtrees"

/** Far from the origin, where nothing has been generated by anything else. */
private const val FAR = 5008
private const val CHUNK = 16

/** The layers a canopy over ordinary ground stands in; a fill takes at most 32768 blocks, and this is 16384. */
private const val LOWEST = 60
private const val HIGHEST = 123
