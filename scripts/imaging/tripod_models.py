#!/usr/bin/env python3
"""
The tripod's models and texture, from Jonah's Blockbench project.

    scripts/imaging/tripod_models.py <path to tripod.bbmodel>

Writes `models/block/tripod.json`, `models/block/tripod_head.json`, `blockstates/tripod.json`, `models/item/tripod.json`,
`items/tripod.json` and `textures/block/tripod.png` (the project's embedded texture) under the companion's assets. Run it
again whenever the project changes.

The tripod is nearly two blocks tall and stands in two, as a door does: the lower half's model is the whole of it, and
the upper half's, the head, has nothing in it but the particle the head breaks into. The lower half is turned by its
facing so its pair of legs stands toward whoever placed it.

The project holds two groups: `tripod`, which is what is written, and `image_recorder`, a reference for where a
recorder stands on it, which is not. That reference fixes the pivot a mounted recorder turns about, the middle of its
base: `ImageRecorderBlock.MOUNTED_PIVOT_HEIGHT` says it in code, and this checks the two agree. An element the project
turns about several axes keeps its angles as 26.3's three-axis element rotation, which applies x, then y, then z, as
Blockbench does.
"""
import base64
import json
import sys
from pathlib import Path

ASSETS = Path(__file__).resolve().parents[2] / "imaging/common/src/main/resources/assets/agesandtheart_imaging"
TEXTURE = "agesandtheart_imaging:block/tripod"
TEXTURE_FILE = ASSETS / "textures/block/tripod.png"

# Where a mounted recorder's base stands, in the model's pixels: kept in step with `ImageRecorderBlock`.
PIVOT_HEIGHT = 22

# The model's pair of legs stands on its north side, toward a player who placed it facing south; the blockstate turns it
# so the pair stands toward whoever placed it, whichever way they faced. Kept in step with `image_recorder_models.py`,
# which turns a mounted recorder's tripod the same way.
FACING_TURNS = {"south": 0, "west": 90, "north": 180, "east": 270}


def group_named(project, name):
    groups = [g for g in project["groups"] if g["name"] == name]
    assert len(groups) == 1, f"one group named {name}"
    return groups[0]["uuid"]


def elements_under(outliner, group_uuid):
    """The uuids of every element in the outliner under [group_uuid]."""
    def walk(nodes, inside):
        for node in nodes:
            if isinstance(node, dict):
                yield from walk(node.get("children", []), inside or node["uuid"] == group_uuid)
            elif inside:
                yield node
    return set(walk(outliner, False))


def element_of(e, width, height):
    assert e.get("stretch", [1, 1, 1]) == [1, 1, 1], (
        f"{e.get('name')} is stretched in Blockbench, which a Java model cannot say: set its size instead"
    )
    out = {"from": e["from"], "to": e["to"]}
    rotation = e.get("rotation")
    if rotation and any(rotation):
        axes = [i for i, angle in enumerate(rotation) if angle]
        if len(axes) == 1:
            out["rotation"] = {"angle": rotation[axes[0]], "axis": "xyz"[axes[0]], "origin": e["origin"]}
        else:
            out["rotation"] = {"origin": e["origin"], "x": rotation[0], "y": rotation[1], "z": rotation[2]}
    faces = {}
    for name, face in e["faces"].items():
        if face.get("texture") is None:
            continue
        u1, v1, u2, v2 = face["uv"]
        f = {"uv": [u1 * 16 / width, v1 * 16 / height, u2 * 16 / width, v2 * 16 / height], "texture": "#0"}
        if face.get("rotation"):
            f["rotation"] = face["rotation"]
        faces[name] = f
    out["faces"] = faces
    return out


def main():
    project = json.loads(Path(sys.argv[1]).read_text())
    assert project["meta"]["model_format"] == "java_block" and not project["meta"]["box_uv"]
    width, height = project["resolution"]["width"], project["resolution"]["height"]

    tripod = elements_under(project["outliner"], group_named(project, "tripod"))
    recorder = elements_under(project["outliner"], group_named(project, "image_recorder"))
    by_uuid = {e["uuid"]: e for e in project["elements"]}
    base = min(by_uuid[u]["from"][1] for u in recorder)
    assert base == PIVOT_HEIGHT, f"the reference recorder stands at {base} pixels, and the code says {PIVOT_HEIGHT}"

    elements = [element_of(e, width, height) for e in project["elements"] if e["uuid"] in tripod]
    block = {
        "_comment": "Generated by scripts/imaging/tripod_models.py from Jonah's Blockbench project; edit the project and "
                    "run it again.",
        "textures": {"0": TEXTURE, "particle": TEXTURE},
        "elements": elements,
    }
    (ASSETS / "models/block").mkdir(parents=True, exist_ok=True)
    (ASSETS / "models/block/tripod.json").write_text(json.dumps(block, indent=2) + "\n")
    head = {
        "_comment": "Generated by scripts/imaging/tripod_models.py: the tripod's upper half, drawn by its lower half's model.",
        "textures": {"particle": TEXTURE},
    }
    (ASSETS / "models/block/tripod_head.json").write_text(json.dumps(head, indent=2) + "\n")
    variants = {"half=upper": {"model": "agesandtheart_imaging:block/tripod_head"}}
    for facing, y in FACING_TURNS.items():
        variant = {"model": "agesandtheart_imaging:block/tripod"}
        if y:
            variant["y"] = y
        variants[f"facing={facing},half=lower"] = variant
    halves = {"variants": variants}
    (ASSETS / "blockstates").mkdir(parents=True, exist_ok=True)
    (ASSETS / "blockstates/tripod.json").write_text(json.dumps(halves, indent=2) + "\n")
    item = {"parent": "agesandtheart_imaging:block/tripod"}
    if project.get("display"):
        item["display"] = project["display"]
    (ASSETS / "models/item/tripod.json").write_text(json.dumps(item, indent=2) + "\n")
    (ASSETS / "items/tripod.json").write_text(
        json.dumps({"model": {"type": "minecraft:model", "model": "agesandtheart_imaging:item/tripod"}}) + "\n"
    )

    assert len(project["textures"]) == 1, "the tripod is one texture"
    source = project["textures"][0]["source"]
    assert source.startswith("data:image/png;base64,"), "the texture is embedded in the project"
    TEXTURE_FILE.parent.mkdir(parents=True, exist_ok=True)
    TEXTURE_FILE.write_bytes(base64.b64decode(source.split(",", 1)[1]))
    print(f"{len(elements)} tripod elements written; the recorder's base stands at {base} pixels")


main()
