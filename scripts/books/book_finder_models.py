#!/usr/bin/env python3
"""
The book finder's models, and its frame's, from Jonah's Blockbench project.

    scripts/books/book_finder_models.py <path to book_finder.bbmodel>

Writes, under the mod's assets:

- `models/block/book_finder_frame.json`, the `static` group: the frame a finder and every frame on its wall share, its
  indicator tinted and drawn full-bright.
- `models/block/book_finder_<part>.json` for each part `BookFinderRenderer` moves: the chassis, the extractor's rails,
  its rotator, the rotator's two paddles, the lectern's arms and its book surface. The left paddle is the one on the left
  as the wall is faced, which in the model's frame is east. Each is where the project has it, at rest, so the renderer's
  pivots are the project's pixels.
- `models/item/book_finder.json`, the whole finder as the project has it, with the project's display.
- `blockstates/book_finder.json`: the frame model, turned by facing, for the placed finder, and each part unturned
  for the `part` the renderer asks for (`BookFinderBlock.PART`).

The project's `reference` group, a vanilla shelf and lectern to measure against, is not written. A face Blockbench has
no texture on is given a dark pixel of the frame's texture until it has one, and a face of no area is left out.
Run it again whenever the project changes.
"""
import json
import sys
from pathlib import Path

ASSETS = Path(__file__).resolve().parents[2] / "common/src/main/resources/assets/agesandtheart"
FRAME_TEXTURE = "agesandtheart:block/book_finder_frame"

# A face with no texture yet: one dark pixel of the frame's.
UNTEXTURED = {"uv": [5, 0, 6, 1], "texture": "#frame"}

# The project's group holding the extractor: its rails, its paddles, and the rotator group they turn with.
EXTRACTOR = "upper extractor"
ROTATOR = "rotator"

# The parts the renderer draws: a group of the project, and which of its elements, by what they are.
PARTS = {
    "chassis": ("chassis", "all"),
    "extractor": (EXTRACTOR, "rails"),
    "rotator": (ROTATOR, "all"),
    "left_paddle": (EXTRACTOR, "left paddle"),
    "right_paddle": (EXTRACTOR, "right paddle"),
    "lectern": ("lectern", "arms"),
    "book_surface": ("lectern", "book surface"),
}

# The middle of the rotator, across; a paddle east of it is the left one.
RING_MIDDLE_ACROSS = 8

FACING_TURNS = {"north": 0, "east": 90, "south": 180, "west": 270}

GENERATED = "Generated by scripts/books/book_finder_models.py from Jonah's Blockbench project; edit the project and run it again."


def group_named(project, name, within=None):
    """The uuid of the one group called [name], under the group [within] where the reference has one of the same name."""
    names = {g["uuid"]: g["name"] for g in project["groups"]}

    def walk(nodes, inside):
        for node in nodes:
            if isinstance(node, dict):
                if inside and names[node["uuid"]] == name:
                    yield node["uuid"]
                yield from walk(node.get("children", []), inside or names[node["uuid"]] == within)

    groups = list(walk(project["outliner"], within is None))
    assert len(groups) == 1, f"one group named {name}"
    return groups[0]


def elements_under(outliner, group_uuid):
    """The uuids of every element in the outliner under [group_uuid], in the outliner's order."""
    def walk(nodes, inside):
        for node in nodes:
            if isinstance(node, dict):
                yield from walk(node.get("children", []), inside or node["uuid"] == group_uuid)
            elif inside:
                yield node
    return list(walk(outliner, False))


def is_paddle(element):
    """A paddle is a plane on its side, reaching from the extractor's ring toward the lectern."""
    size = [b - a for a, b in zip(element["from"], element["to"])]
    return size[0] == 0 and size[2] > 0


def is_book_surface(element):
    return element["name"] == "book surface"


def is_one_of(element, which, rotator):
    if which == "all":
        return True
    if which == "rails":
        return not is_paddle(element) and element["uuid"] not in rotator
    if which == "left paddle":
        return is_paddle(element) and element["from"][0] > RING_MIDDLE_ACROSS
    if which == "right paddle":
        return is_paddle(element) and element["from"][0] < RING_MIDDLE_ACROSS
    if which == "book surface":
        return is_book_surface(element)
    if which == "arms":
        return not is_book_surface(element)
    raise ValueError(which)


def has_area(face, size):
    dx, dy, dz = size
    return {"north": dx * dy, "south": dx * dy, "east": dz * dy, "west": dz * dy, "up": dx * dz, "down": dx * dz}[face] > 0


def number(value):
    return int(value) if float(value).is_integer() else value


def element_of(e, texture_keys):
    assert e.get("stretch", [1, 1, 1]) == [1, 1, 1], f"{e.get('name')} is stretched, which a Java model cannot say"
    size = [b - a for a, b in zip(e["from"], e["to"])]
    out = {}
    if e["name"] == "indicator":
        out["name"] = "indicator"
    out["from"] = [number(v) for v in e["from"]]
    out["to"] = [number(v) for v in e["to"]]
    rotation = e.get("rotation")
    if rotation and any(rotation):
        axes = [i for i, angle in enumerate(rotation) if angle]
        assert len(axes) == 1, f"{e['name']} turns about more than one axis"
        out["rotation"] = {"angle": number(rotation[axes[0]]), "axis": "xyz"[axes[0]], "origin": [number(v) for v in e["origin"]]}
    if e["name"] == "indicator":
        out["light_emission"] = 15
        out["shade"] = False
    faces = {}
    for name in ["north", "east", "south", "west", "up", "down"]:
        face = e["faces"].get(name)
        if face is None or not has_area(name, size):
            continue
        if face.get("texture") is None:
            faces[name] = dict(UNTEXTURED)
            continue
        f = {"uv": [number(v) for v in face["uv"]], "texture": "#" + texture_keys[face["texture"]]}
        if face.get("rotation"):
            f["rotation"] = face["rotation"]
        if e["name"] == "indicator":
            f["tintindex"] = 0
        faces[name] = f
    out["faces"] = faces
    return out


def texture_keys_of(project):
    """Each of the project's textures, by its index, as a model's key; and each key's texture."""
    keys, textures = {}, {}
    for index, texture in enumerate(project["textures"]):
        name = texture["name"].removesuffix(".png")
        if name == "book_finder_frame_texture":
            key, location = "frame", FRAME_TEXTURE
        else:
            key, location = name, f"minecraft:block/{name}"
        keys[index] = key
        textures[key] = location
    return keys, textures


def model_of(elements, texture_keys, textures, comment):
    used = sorted({face["texture"][1:] for e in elements for face in e["faces"].values()})
    return {
        "_comment": comment,
        "textures": {**{key: textures[key] for key in used}, "particle": FRAME_TEXTURE},
        "elements": elements,
    }


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + "\n")


def main():
    project = json.loads(Path(sys.argv[1]).read_text())
    assert project["meta"]["model_format"] == "java_block" and not project["meta"]["box_uv"]
    assert project["resolution"] == {"width": 16, "height": 16}, "every texture is 16 pixels square"
    by_uuid = {e["uuid"]: e for e in project["elements"]}
    keys, textures = texture_keys_of(project)
    outliner = project["outliner"]

    static = [element_of(by_uuid[u], keys) for u in elements_under(outliner, group_named(project, "static"))]
    write(ASSETS / "models/block/book_finder_frame.json", {
        **model_of(static, keys, textures, GENERATED),
        "parent": "minecraft:block/block",
    })

    rotator = set(elements_under(outliner, group_named(project, ROTATOR, within="book finder")))
    for part, (group, which) in PARTS.items():
        uuids = elements_under(outliner, group_named(project, group, within="book finder"))
        chosen = [by_uuid[u] for u in uuids if is_one_of(by_uuid[u], which, rotator)]
        assert chosen, f"nothing in {part}"
        if part.endswith("paddle"):
            assert len(chosen) == 1, f"{group} has {len(chosen)} {which}s"
        write(ASSETS / f"models/block/book_finder_{part}.json",
              model_of([element_of(e, keys) for e in chosen], keys, textures, GENERATED))

    whole = [element_of(by_uuid[u], keys) for u in elements_under(outliner, group_named(project, "book finder"))]
    item = model_of(whole, keys, textures, GENERATED)
    item["parent"] = "minecraft:block/block"
    if project.get("display"):
        item["display"] = project["display"]
    write(ASSETS / "models/item/book_finder.json", item)

    multipart = []
    for facing, y in FACING_TURNS.items():
        apply = {"model": "agesandtheart:block/book_finder_frame"}
        if y:
            apply["y"] = y
        multipart.append({"when": {"part": "static", "facing": facing}, "apply": apply})
    for part in PARTS:
        multipart.append({"when": {"part": part}, "apply": {"model": f"agesandtheart:block/book_finder_{part}"}})
    write(ASSETS / "blockstates/book_finder.json", {
        "_comment": "Generated by scripts/books/book_finder_models.py. Only `part=static` is ever placed; the other parts "
                    "are drawn moving by `BookFinderRenderer`, which turns them by facing itself.",
        "multipart": multipart,
    })
    print(f"{len(static)} static elements, {len(whole)} in the whole finder, {len(PARTS)} moving parts written")


main()
