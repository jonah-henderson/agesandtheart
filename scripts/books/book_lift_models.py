#!/usr/bin/env python3
"""
The book lift's models, from Jonah's Blockbench project.

    scripts/books/book_lift_models.py <path to book_lift.bbmodel>

Writes, under the mod's assets:

- `models/block/book_lift_frame_<part>.json`, the project's `base` group: a frame's box, its buttons' panel to the
  front and its wheels to either side. A base has the hold on top, where the shelves go in and out, and a cap has it
  underneath; each has the other's face on its far side. A frame between two columns has no hold, and the far face on
  both. The back is the front's panel.
- `models/block/book_lift_button_<button>.json`, `_pressed.json` and `_locked.json`, each of the `buttons` group's
  buttons out, in by half a pixel and lit, and in and dark. Out, its faces take tint 1, the dark grey; pressed, tint 0,
  the yellow; locked, while nothing powers the lift, tint 2, the same grey (`AgeTints`). A button's face mapped onto pixels of the texture not yet painted is put on the button grey
  instead, and named, so it has no holes.
- `models/block/book_lift_platform.json`, the `platform` group a block lower, where it rests in a shelf's block, tinted
  by the chain it hangs on (`AgeTints`).
- `blockstates/book_lift_frame.json`: the box by `part`, and where it has `buttons`, each out or in by `pressed`, or all
  locked where it is not `powered`, all turned by facing.
- `blockstates/book_lift_shelf.json`: the platform turned by facing while `shows=platform`, and nothing otherwise.
- `items/book_lift_frame.json` and `models/item/book_lift_frame.json`: a base, its buttons locked as a frame of no lift
  has them, with the project's display.
- `textures/block/book_lift_frame.png` and `book_lift_platform.png`, copied from where the project keeps them.

The project's `reference flat book` group is not written. Run it again whenever the project changes.
"""
import json
import shutil
import sys
from pathlib import Path

from PIL import Image

ASSETS = Path(__file__).resolve().parents[2] / "common/src/main/resources/assets/agesandtheart"

# The project's own textures, by their name in the project, as the model's key and the mod's texture.
OWN_TEXTURES = {
    "book_lift_texture": ("frame", "book_lift_frame"),
    "book_platform_texture": ("platform", "book_lift_platform"),
}

# A Java model's faces are mapped in sixteenths of their texture, however many pixels it has.
MODEL_UV_SPAN = 16

# Each button's group in the project, by the name `LiftButton` serialises it as.
BUTTONS = {
    "stop": "stop",
    "step_up": "step up",
    "step_down": "step down",
    "continuous_up": "continuous up",
    "continuous_down": "continuous down",
}

# How far a pressed button goes in, toward the frame's back.
PRESSED_IN = 0.5

# A pressed button's tint, and one out.
LIT, DULL, LOCKED = 0, 1, 2

# The yellow and the dull grey `AgeTints` draws the buttons in, for the item.
LIT_TINT = 0xFFDD6E
DULL_TINT = 0x5A5A5A
LOCKED_TINT = DULL_TINT

# The button grey, where it is painted: the stop button's front, in the project's UV.
BUTTON_GREY_UV = [8, 16, 10, 18]

# The platform is modelled in the block above the frame, where a shelf is.
PLATFORM_DROP = 16

FACING_TURNS = {"north": 0, "east": 90, "south": 180, "west": 270}

GENERATED = "Generated by scripts/books/book_lift_models.py from Jonah's Blockbench project; edit the project and run it again."


def group_named(project, name):
    groups = [g["uuid"] for g in project["groups"] if g["name"] == name]
    assert len(groups) == 1, f"one group named {name}"
    return groups[0]


def elements_under(project, name):
    """Every element in the outliner under the group called [name], in the outliner's order."""
    group_uuid = group_named(project, name)
    by_uuid = {e["uuid"]: e for e in project["elements"]}

    def walk(nodes, inside):
        for node in nodes:
            if isinstance(node, dict):
                yield from walk(node.get("children", []), inside or node["uuid"] == group_uuid)
            elif inside:
                yield by_uuid[node]
    return list(walk(project["outliner"], False))


def number(value):
    return int(value) if float(value).is_integer() else round(value, 4)


def moved(point, by):
    return [number(v + d) for v, d in zip(point, by)]


def element_of(e, texture_keys, uv_scale, offset=(0, 0, 0), tint=None, lit=False, faces_from=None):
    """The project's element [e] as a Java model's, moved by [offset]; [faces_from] puts another face's mapping on a face."""
    assert e.get("stretch", [1, 1, 1]) == [1, 1, 1], f"{e.get('name')} is stretched, which a Java model cannot say"
    out = {"from": moved(e["from"], offset), "to": moved(e["to"], offset)}
    rotation = e.get("rotation")
    if rotation and any(rotation):
        axes = [i for i, angle in enumerate(rotation) if angle]
        assert len(axes) == 1, f"{e['name']} turns about more than one axis"
        out["rotation"] = {"angle": number(rotation[axes[0]]), "axis": "xyz"[axes[0]], "origin": moved(e["origin"], offset)}
    if lit:
        out["light_emission"] = 15
        out["shade"] = False
    faces = {}
    for name in ["north", "east", "south", "west", "up", "down"]:
        face = e["faces"][(faces_from or {}).get(name, name)]
        assert face.get("texture") is not None, f"{e['name']}'s {name} face has no texture"
        f = {"uv": [number(v * uv_scale) for v in face["uv"]], "texture": "#" + texture_keys[face["texture"]]}
        if face.get("rotation"):
            f["rotation"] = face["rotation"]
        if tint is not None:
            f["tintindex"] = tint
        faces[name] = f
    out["faces"] = faces
    return out


def painted_everywhere(image, uv, uv_scale_to_pixels):
    """Whether every pixel under [uv] of [image] is opaque."""
    u0, v0, u1, v1 = [value * uv_scale_to_pixels for value in uv]
    xs = range(int(min(u0, u1)), max(int(min(u0, u1)) + 1, int(max(u0, u1))))
    ys = range(int(min(v0, v1)), max(int(min(v0, v1)) + 1, int(max(v0, v1))))
    return all(image.getpixel((x, y))[3] == 255 for x in xs for y in ys)


def onto_the_button_grey(element, image, uv_scale_to_pixels):
    """[element] with each face mapped where nothing is painted moved onto the button grey, naming each."""
    assert painted_everywhere(image, BUTTON_GREY_UV, uv_scale_to_pixels), "the button grey is painted"
    faces = {}
    for name, face in element["faces"].items():
        if painted_everywhere(image, face["uv"], uv_scale_to_pixels):
            faces[name] = face
        else:
            print(f"warning: {element['name']}'s {name} face, at {face['uv']}, reaches unpainted pixels; put on the button grey")
            faces[name] = {**face, "uv": BUTTON_GREY_UV, "rotation": 0}
    return {**element, "faces": faces}


def with_cullfaces(element):
    """The box's faces, each hidden where a block beside it covers it."""
    for name, face in element["faces"].items():
        face["cullface"] = name
    return element


def texture_keys_of(project):
    keys, textures = {}, {}
    for index, texture in enumerate(project["textures"]):
        key, ours = OWN_TEXTURES[texture["name"].removesuffix(".png")]
        keys[index] = key
        textures[key] = f"agesandtheart:block/{ours}"
    return keys, textures


def copy_own_textures(project, project_path):
    for texture in project["textures"]:
        _, ours = OWN_TEXTURES[texture["name"].removesuffix(".png")]
        shutil.copyfile((project_path.parent / texture["relative_path"]).resolve(), ASSETS / f"textures/block/{ours}.png")


def model_of(elements, textures, particle="frame"):
    used = sorted({face["texture"][1:] for e in elements for face in e["faces"].values()})
    return {
        "_comment": GENERATED,
        "textures": {**{key: textures[key] for key in used}, "particle": textures[particle]},
        "elements": elements,
    }


def write(path, value):
    path.write_text(json.dumps(value, indent=2) + "\n")


def turned(model, facing):
    applied = {"model": model}
    if FACING_TURNS[facing]:
        applied["y"] = FACING_TURNS[facing]
    return applied


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    project_path = Path(sys.argv[1])
    project = json.loads(project_path.read_text())
    keys, textures = texture_keys_of(project)
    uv_scale = MODEL_UV_SPAN / project["resolution"]["width"]
    copy_own_textures(project, project_path)

    [box] = elements_under(project, "base")
    # The cap is the base with its hold underneath, and a frame between has the far face both ways; the back of every
    # one is the front's panel.
    faces_of_each_part = {
        "base": {"south": "north"},
        "cap": {"south": "north", "up": "down", "down": "up"},
        "between": {"south": "north", "up": "down"},
    }
    for part, faces_from in faces_of_each_part.items():
        model = model_of([with_cullfaces(element_of(box, keys, uv_scale, faces_from=faces_from))], textures)
        write(ASSETS / f"models/block/book_lift_frame_{part}.json", {"parent": "minecraft:block/block", **model})

    frame_texture = next(t for t in project["textures"] if OWN_TEXTURES[t["name"].removesuffix(".png")][0] == "frame")
    frame_image = Image.open((project_path.parent / frame_texture["relative_path"]).resolve()).convert("RGBA")
    to_pixels = frame_image.width / project["resolution"]["width"]

    buttons = {}
    for button, group in BUTTONS.items():
        parts = [onto_the_button_grey(e, frame_image, to_pixels) for e in elements_under(project, group)]
        out = [element_of(e, keys, uv_scale, tint=DULL) for e in parts]
        pressed = [element_of(e, keys, uv_scale, offset=(0, 0, PRESSED_IN), tint=LIT, lit=True) for e in parts]
        locked = [element_of(e, keys, uv_scale, offset=(0, 0, PRESSED_IN), tint=LOCKED) for e in parts]
        buttons[button] = locked
        write(ASSETS / f"models/block/book_lift_button_{button}_locked.json", model_of(locked, textures))
        write(ASSETS / f"models/block/book_lift_button_{button}.json", model_of(out, textures))
        write(ASSETS / f"models/block/book_lift_button_{button}_pressed.json", model_of(pressed, textures))

    platform = [element_of(e, keys, uv_scale, offset=(0, -PLATFORM_DROP, 0), tint=0) for e in elements_under(project, "platform")]
    write(ASSETS / "models/block/book_lift_platform.json", model_of(platform, textures, particle="platform"))

    frame_parts = []
    for facing in FACING_TURNS:
        for part in faces_of_each_part:
            frame_parts.append({"when": {"facing": facing, "part": part}, "apply": turned(f"agesandtheart:block/book_lift_frame_{part}", facing)})
        for button in BUTTONS:
            others = "|".join(b for b in BUTTONS if b != button)
            running = {"facing": facing, "buttons": "true", "powered": "true"}
            frame_parts.append({"when": {**running, "pressed": others}, "apply": turned(f"agesandtheart:block/book_lift_button_{button}", facing)})
            frame_parts.append({"when": {**running, "pressed": button}, "apply": turned(f"agesandtheart:block/book_lift_button_{button}_pressed", facing)})
            locked = {"facing": facing, "buttons": "true", "powered": "false"}
            frame_parts.append({"when": locked, "apply": turned(f"agesandtheart:block/book_lift_button_{button}_locked", facing)})
    write(ASSETS / "blockstates/book_lift_frame.json", {
        "_comment": "[AI] A book lift frame: its box, a base, a cap or a frame between, and, on the one running a lift, its five buttons: the one "
                    "pressed in and lit, or every one in and dark while nothing powers it. " + GENERATED,
        "multipart": frame_parts,
    })

    write(ASSETS / "blockstates/book_lift_shelf.json", {
        "_comment": "[AI] A shelf's platform while the lift is still; while it turns, `BookLiftShelfRenderer` draws the platforms "
                    "sliding, and the chains always. " + GENERATED,
        "multipart": [
            {"when": {"shows": "platform", "facing": facing}, "apply": turned("agesandtheart:block/book_lift_platform", facing)}
            for facing in FACING_TURNS
        ],
    })

    item_elements = [with_cullfaces(element_of(box, keys, uv_scale, faces_from=faces_of_each_part["base"]))]
    for locked in buttons.values():
        item_elements += locked
    write(ASSETS / "models/item/book_lift_frame.json", {
        "parent": "minecraft:block/block",
        **model_of(item_elements, textures),
        "display": project.get("display", {}),
    })
    write(ASSETS / "items/book_lift_frame.json", {
        "_comment": "[AI] A base, its buttons locked, as a frame is placed.",
        "model": {
            "type": "minecraft:model",
            "model": "agesandtheart:item/book_lift_frame",
            "tints": [
                {"type": "minecraft:constant", "value": LIT_TINT},
                {"type": "minecraft:constant", "value": DULL_TINT},
                {"type": "minecraft:constant", "value": LOCKED_TINT},
            ],
        },
    })


if __name__ == "__main__":
    main()
